/// index of `--style` name ("auto" → None). Accepts ids and names, case-insensitive, prefixes ok.
pub fn find(name: &str) -> Result<Option<usize>, String> {
    let n = name.trim().to_lowercase();
    if n == "auto" {
        return Ok(None);
    }
    for (i, s) in STYLES.iter().enumerate() {
        if s.id == n || s.name.to_lowercase() == n {
            return Ok(Some(i));
        }
    }
    let m: Vec<usize> = (0..STYLES.len()).filter(|&i| STYLES[i].id.starts_with(&n) || STYLES[i].name.to_lowercase().starts_with(&n)).collect();
    if m.len() == 1 {
        return Ok(Some(m[0]));
    }
    Err(format!("unknown style '{name}' (auto, {})", STYLES.iter().map(|s| s.id).collect::<Vec<_>>().join(", ")))
}
