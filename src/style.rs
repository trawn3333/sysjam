//! Conductor styles: personalities that steer the whole band (instruments,
//! tempo range, density, drum feel, modes, harmony, synth vs GM, theme quotes,
//! strictness). Selected with ←/→ in the TUI or `--style`.

use crate::harmony::Rel;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Scale {
    Diatonic,
    /// major / minor pentatonic of the player's key
    Penta,
    /// blues scale: b3 / b5 / b7 blue notes (plus the major third in major keys)
    Blues,
    /// pelog-ish five-note scale (0 1 3 7 8) in minor keys, major pentatonic in major
    Pelog,
    /// Phrygian (0 1 3 5 7 8 10): the flat second (industrial)
    Phrygian,
}

/// harmony flavour: extra phrase templates and chord colours
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Harm {
    Pop,
    Drone,
    Jazz,
    Rock,
    Chorale,
    Modal,
    /// 12-bar blues, one bar per chord
    Blues,
    /// I–IV–V country changes
    Country,
    /// techno: one- and two-chord loops
    Loop,
    /// industrial: riff harmony, i–bII / i–bv, locked, sudden semitone drops
    Riff,
    /// biker: a song form (verse / pre-chorus / chorus), one chord per bar, the machine plans it
    Song,
}

/// how the bassist plays in this style
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum BassFeel {
    Band,
    /// walking quarters: chord tones and a chromatic approach (jazz)
    Walk,
    /// boogie-woogie quarters 1-3-5-6-b7-6-5-3 (blues)
    Boogie,
    /// root on 1, fifth on 3 (country)
    BoomChick,
    /// 303-style resonant 16th-note line with slides and slow filter sweeps (techno)
    Acid,
}

/// drum feel
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum DrumFeel {
    Band,
    /// triplet shuffle on the eighths (blues)
    Shuffle,
    /// four-on-the-floor sub kick, off-beat open hats, claps on 2 and 4 (techno)
    FourFloor,
    /// train beat / two-step (country)
    Train,
}

pub struct Style {
    pub id: &'static str,
    pub name: &'static str,
    pub desc: &'static str,
    /// living-tempo ranges: chilling, awakening, alive
    pub tempo: [(f32, f32); 3],
    /// how freely the tempo wanders (1 = default)
    pub tempo_rate: f32,
    /// melodic density multiplier (conductor target) and restraint shift
    pub density: f32,
    /// drummer participation multiplier (grooving weight)
    pub drums: f32,
    /// extra swing on the off-beat sixteenths (0..0.35)
    pub swing: f32,
    /// jazz: ride instead of closed hats
    pub ride: bool,
    /// hand percussion carries the groove (denser aux pattern)
    pub perc_heavy: bool,
    /// favoured GM kits (indices into gm::KITS) and percussion sets (gm::PERC_SETS)
    pub kits: &'static [usize],
    pub perc: &'static [usize],
    /// favoured GM programs per role: Pad, Comp, Lead, Colour, Bass
    pub progs: [&'static [u8]; 5],
    /// GM bass layer also outside the groove (upright, contrabass…)
    pub gm_bass: bool,
    /// multiplier on each player's synth-vs-GM preference
    pub synth: f32,
    /// synth patch kind weights: subtractive, FM, wavetable, pluck
    pub kinds: [f32; 4],
    /// extra synth level (dB) when it is supposed to sit back (Space Cadet only)
    pub syn_front: f32,
    /// favoured key relations for the players' own keys
    pub rels: &'static [(Rel, f32)],
    pub scale: Scale,
    pub harm: Harm,
    /// −1 minor … +1 major preference for modulations
    pub major: f32,
    /// modulation rate multiplier
    pub mod_rate: f32,
    /// theme-quote rate multiplier and favoured sources (substring of collection/composer)
    pub quote: f32,
    pub quote_src: &'static [&'static str],
    /// conductor strictness: clutter thresholds are divided by this (>1 = stricter)
    pub strict: f32,
    /// surge probability multiplier
    pub surge: f32,
    /// industrial texture likelihood multiplier
    pub industrial: f32,
    /// conductor costume: drawn over the figure's top row, and an optional face
    pub hat: &'static str,
    pub face: Option<&'static str>,
    /// speech: announcement, tempo up, tempo down, quote praise, hush word
    pub hello: &'static str,
    pub faster: &'static str,
    pub slower: &'static str,
    pub praise: &'static str,
    pub hush: &'static str,
    pub bass_feel: BassFeel,
    pub drum_feel: DrumFeel,
    /// techno: drums always in, synth not pushed back, but a hard 4-5 layer cap
    pub relax: bool,
    /// industrial: the rage machine (src/rage.rs) takes bass, drums and the guitar wall;
    /// restraint, minimal drums and synth-in-back are off, it is meant to be intense
    pub rage: Option<crate::rage::Kind>,
}

